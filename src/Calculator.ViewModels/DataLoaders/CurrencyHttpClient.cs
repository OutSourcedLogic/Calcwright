        /// <summary>Country/currency names and symbols, in the JSON shape CurrencyDataLoader expects.</summary>
        public Task<string> GetCurrencyMetadataAsync()
        {
#if VIEWMODEL_FOR_UT
            if (ForceWebFailure)
            {
                return Task.FromException<string>(new Exception("Forced web failure for unit testing"));
            }
#endif
            if (UseSampleData)
            {
                return Task.FromResult(SampleCurrencyStaticData);
            }

            var array = new JsonArray();
            foreach (var row in CurrencyNames.All)
            {
                var obj = new JsonObject
                {
                    ["CountryCode"] = JsonValue.CreateStringValue(row[0]),
                    ["CountryName"] = JsonValue.CreateStringValue(row[1]),
                    ["CurrencyCode"] = JsonValue.CreateStringValue(row[0]),
                    ["CurrencyName"] = JsonValue.CreateStringValue(row[2]),
                    ["CurrencySymbol"] = JsonValue.CreateStringValue(row[3]),
                };
                array.Add(obj);
            }
            return Task.FromResult(array.Stringify());
        }

        /// <summary>
        /// Rates as units of each currency per 1 US dollar, in the JSON shape CurrencyDataLoader expects
        /// ([{ "An": code, "Rt": rate }, ...]). Returns null if the rates can't be fetched, so the loader
        /// falls back to its cached rates (or shows its normal "couldn't update" state).
        /// </summary>
        public async Task<string> GetCurrencyRatiosAsync()
        {
#if VIEWMODEL_FOR_UT
            if (ForceWebFailure)
            {
                throw new Exception("Forced web failure for unit testing");
            }
#endif
            if (UseSampleData)
            {
                return SampleCurrencyConverterData;
            }

            string body;
            try
            {
                body = await _sharedClient.GetStringAsync(new Uri(RatesUri));
            }
            catch (Exception)
            {
                return null;
            }

            return ConvertRatesResponse(body);
        }

        /// <summary>Turns an ExchangeRate-API "latest" response into the loader's ratio JSON, or null if it isn't valid.</summary>
        internal static string ConvertRatesResponse(string body)
        {
            if (!JsonObject.TryParse(body ?? string.Empty, out JsonObject response))
            {
                return null;
            }
            if (!response.ContainsKey("result") || response.GetNamedString("result", string.Empty) != "success"
                || !response.ContainsKey("rates"))
            {
                return null;
            }

            JsonObject rates = response.GetNamedObject("rates");
            var sb = new StringBuilder("[");
            bool first = true;
            foreach (var kvp in rates)
            {
                if (kvp.Value.ValueType != JsonValueType.Number)
                {
                    continue;
                }
                double rate = kvp.Value.GetNumber();
                if (!(rate > 0) || double.IsInfinity(rate))
                {
                    continue;
                }

                if (!first)
                {
                    sb.Append(',');
                }
                first = false;
                sb.Append("{\"An\":")
                  .Append(JsonValue.CreateStringValue(kvp.Key).Stringify())
                  .Append(",\"Rt\":")
                  .Append(rate.ToString("R", CultureInfo.InvariantCulture))
                  .Append('}');
            }
            sb.Append(']');

            return first ? null : sb.ToString();
        }
    }
