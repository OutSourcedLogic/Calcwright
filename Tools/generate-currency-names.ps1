# Regenerates src\Calculator.ViewModels\DataLoaders\CurrencyNames.g.cs: English country name, currency
# name and symbol for every currency the free ExchangeRate-API endpoint quotes.
# Names come from Windows' own region data (RegionInfo); a few shared or special currencies are set by hand.
# Currencies with no name data are left out, so the converter never lists something it can't describe.
param([string]$OutFile = (Join-Path $PSScriptRoot '..\src\Calculator.ViewModels\DataLoaders\CurrencyNames.g.cs'))
$ErrorActionPreference = 'Stop'

$rates = (Invoke-RestMethod 'https://open.er-api.com/v6/latest/USD' -TimeoutSec 30).rates
$codes = $rates.PSObject.Properties.Name | Sort-Object

# Currencies shared by several countries, or not tied to one region.
$manual = @{
    'EUR' = @('Europe', 'Euro', '€')
    'XAF' = @('Central Africa', 'Central African CFA Franc', 'FCFA')
    'XOF' = @('West Africa', 'West African CFA Franc', 'CFA')
    'XCD' = @('Eastern Caribbean', 'East Caribbean Dollar', 'EC$')
    'XPF' = @('French Pacific Territories', 'CFP Franc', '₣')
    'XDR' = @('International Monetary Fund', 'Special Drawing Rights', 'SDR')
    'ANG' = @('Curaçao and Sint Maarten', 'Netherlands Antillean Guilder', 'ƒ')
    'XCG' = @('Curaçao and Sint Maarten', 'Caribbean Guilder', 'Cg')
    'USD' = @('United States', 'US Dollar', '$')
    'GBP' = @('United Kingdom', 'British Pound', '£')
    'AUD' = @('Australia', 'Australian Dollar', '$')
    'NZD' = @('New Zealand', 'New Zealand Dollar', '$')
    'CHF' = @('Switzerland', 'Swiss Franc', 'CHF')
    'INR' = @('India', 'Indian Rupee', '₹')
}

# Index Windows region data by currency code; prefer the region whose code matches the first two letters.
$byCurrency = @{}
foreach ($culture in [Globalization.CultureInfo]::GetCultures([Globalization.CultureTypes]::SpecificCultures)) {
    try { $region = New-Object Globalization.RegionInfo($culture.Name) } catch { continue }
    $code = $region.ISOCurrencySymbol
    if (-not $byCurrency.ContainsKey($code)) { $byCurrency[$code] = @() }
    $byCurrency[$code] += $region
}

$rows = @(); $skipped = @()
foreach ($code in $codes) {
    if ($manual.ContainsKey($code)) { $rows += ,@($code, $manual[$code][0], $manual[$code][1], $manual[$code][2]); continue }
    $regions = $byCurrency[$code]
    if (-not $regions) { $skipped += $code; continue }
    $pick = ($regions | Where-Object { $_.TwoLetterISORegionName -eq $code.Substring(0, 2) } | Select-Object -First 1)
    if (-not $pick) { $pick = $regions[0] }
    $rows += ,@($code, $pick.EnglishName, $pick.CurrencyEnglishName, $pick.CurrencySymbol)
}

function Esc([string]$s) { $s.Replace('\', '\\').Replace('"', '\"') }
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated> by tools\generate-currency-names.ps1. Re-run that script instead of editing by hand. </auto-generated>')
[void]$sb.AppendLine('namespace CalculatorApp.ViewModel.DataLoaders')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    internal static class CurrencyNames')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        // Currency code, country (or region) name, currency name, symbol.')
[void]$sb.AppendLine('        internal static readonly string[][] All =')
[void]$sb.AppendLine('        {')
foreach ($r in $rows) { [void]$sb.AppendLine(('            new[] {{ "{0}", "{1}", "{2}", "{3}" }},' -f (Esc $r[0]), (Esc $r[1]), (Esc $r[2]), (Esc $r[3]))) }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object Text.UTF8Encoding($true)))

"Wrote $($rows.Count) currencies to $OutFile"
if ($skipped) { "No name data (left out): $($skipped -join ', ')" }
